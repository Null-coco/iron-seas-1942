const TUBES_PER_MOUNT = [['五连装', 5], ['四连装', 4], ['三连装', 3], ['二连装', 2], ['水下', 1]];
function expandTorpedoes(list) {
  const out = [];
  for (const t of list) {
    const mounts = t.tubes;
    let per = 3;
    for (const [pat, n] of TUBES_PER_MOUNT) if (String(t.mountLabel).includes(pat)) { per = n; break; }
    for (let i = 0; i < mounts; i++) out.push(Object.assign({}, t, { mountLabel: t.mountLabel + ' #' + (i + 1), tubes: per }));
  }
  return out;
}
