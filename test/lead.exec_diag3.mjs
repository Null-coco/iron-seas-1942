import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { World } from '../src/sim/world.js';
import { ShipDatabase } from '../src/sim/data.js';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const R = path.join(__dirname, '..');
const j = (p) => JSON.parse(fs.readFileSync(path.join(R, p), 'utf8'));
const db = ShipDatabase.fromMany([j('data/ships_axis.json'), j('data/ships_allied.json')]);
const sc = j('data/scenarios.json').scenarios.find((s) => s.id === 'denmark_strait_1941');
const w = new World({ scenario: sc, database: db, seed: 7, playerSide: 'ALLIED', aiOpts: { backend: 'LOCAL' } });
const ai = w.ai['AXIS'];
console.log('role=' + ai.role + ' backend=' + ai.backend);
ai.connectLLM('', { model: 'stub' });
let calls = 0;
ai.setLLMCall(async (a) => { calls++; return JSON.stringify({ reasoning: 'stub', intent: 'stub', commands: [{ shipId: 'bismarck', kind: 'SET_COURSE', params: { heading: 200 } }] }); });
ai.intervalS = 1;
w.advance(30);
console.log('llmCall 调用次数=' + calls + ' pending=' + ai.pendingRequest + ' decisions=' + ai.status.decisions + ' issued=' + ai.status.commandsIssued + ' rejected=' + ai.status.commandsRejected + ' rateLimited=' + ai.status.rateLimited);
console.log('AI_REMOTE 命令数=' + w.commands.filter((c) => c.source === 'AI_REMOTE').length);
const evs = w.events.history.filter((e) => e.type === 'ai.decision' && e.side === 'AXIS');
console.log('AXIS ai.decision 事件=' + evs.length + (evs.length ? ' 最后一条：' + JSON.stringify({ commands: evs[evs.length - 1].commands, role: evs[evs.length - 1].role }) : ''));
