import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { World } from '../src/sim/world.js';
import { ShipDatabase } from '../src/sim/data.js';
import { normalizeCommand } from '../src/ai/nl.js';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const R = path.join(__dirname, '..');
const j = (p) => JSON.parse(fs.readFileSync(path.join(R, p), 'utf8'));
const db = ShipDatabase.fromMany([j('data/ships_axis.json'), j('data/ships_allied.json')]);
const sc = j('data/scenarios.json').scenarios.find((s) => s.id === 'denmark_strait_1941');
const w = new World({ scenario: sc, database: db, seed: 7, playerSide: 'ALLIED', aiOpts: { backend: 'LOCAL' } });
console.log('归一化测试：' + JSON.stringify(normalizeCommand({ shipId: 'bismarck', kind: 'SET_COURSE', params: { heading: 200 } })));
const ai = w.ai['AXIS'];
ai.connectLLM('', { model: 'stub' });
ai.setLLMCall(async () => JSON.stringify({ reasoning: 'stub', intent: 'stub', commands: [{ shipId: 'bismarck', kind: 'SET_COURSE', params: { heading: 200 } }] }));
ai.intervalS = 1;
w.advance(30);
for (const e of w.events.history.filter((x) => x.type === 'ai.decision').slice(-2)) console.log('ai.decision: ' + JSON.stringify({ commands: e.commands, rejected: e.rejected, reasoning: String(e.reasoning || '').slice(0, 40), rateLimited: e.rateLimited }));
console.log('AI 命令白名单/状态：' + JSON.stringify(Object.keys(ai.status)));
console.log('minDecisionIntervalS=' + ai.minDecisionIntervalS + ' maxCommandsPerDecision=' + ai.maxCommandsPerDecision);
