import fs from 'node:fs';
import { World } from '../src/sim/world.js';
import { ShipDatabase } from '../src/sim/data.js';
const j = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const db = ShipDatabase.fromMany([j('data/ships_axis.json'), j('data/ships_allied.json')]);
const sc = j('data/scenarios.json').scenarios.find((s) => s.id === 'denmark_strait_1941');
const w = new World({ scenario: sc, database: db, seed: 1001, playerSide: 'ALLIED', aiOpts: { backend: 'LOCAL' }, landData: j('data/land.json'), depthData: j('data/depth.json') });
for (const s of ['ALLIED', 'AXIS']) w.ai[s].autoCommand = true;
const parts = {}, pen = {}, magHits = [], turretHits = [];
w.events.on('gun.hit', (e) => { parts[e.hitPart] = (parts[e.hitPart] || 0) + 1; if (e.penetrated) pen[e.hitPart] = (pen[e.hitPart] || 0) + 1; });
w.events.on('dam.magazine', (e) => magHits.push({ t: Math.round(w.t), ship: e.name || e.ship, risk: e.magRisk, res: e.result, flash: e.flashProtected }));
w.events.on('dam.subsystem', (e) => { if (e.kind === 'TURRET') turretHits.push({ t: Math.round(w.t), ship: e.name, health: e.health, destroyed: e.destroyed }); });
w.advance(1200);
const total = Object.values(parts).reduce((a, b) => a + b, 0);
console.log('命中部位分布（' + total + ' 发）:');
for (const [k, v] of Object.entries(parts).sort((a, b) => b[1] - a[1])) console.log('  ' + k.padEnd(15) + v + ' (' + (100 * v / total).toFixed(0) + '%)  穿透 ' + (pen[k] || 0));
console.log('\n炮塔受损事件 ' + turretHits.length + ' 次，其中击毁 ' + turretHits.filter((x) => x.destroyed).length + ' 次');
console.log('弹药库命中事件 ' + magHits.length + ' 次：' + JSON.stringify(magHits.slice(0, 6)));
console.log('殉爆 ' + w.events.history.filter((e) => e.type === 'dam.magazine' && e.result === 'detonation').length + ' 次');
const hood = w.ships.find((s) => (s.id || '').indexOf('hood') >= 0);
console.log('Hood 在航 ' + hood.isAfloat + ' 主炮 ' + hood.mainBatteries.filter((b) => !b.destroyed).length + '/4 进水 ' + Math.round(hood.floodedM3));
const bis = w.ships.find((s) => (s.id || '').indexOf('bismarck') >= 0);
console.log('Bismarck 主炮 ' + bis.mainBatteries.filter((b) => !b.destroyed).length + '/4 速度上限 ' + bis.speedCapKn.toFixed(1) + ' 进水 ' + Math.round(bis.floodedM3));
