import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { World } from '../src/sim/world.js';
import { ShipDatabase } from '../src/sim/data.js';
import { AICommander } from '../src/ai/bridge.js';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const R = path.join(__dirname, '..');
const j = (p) => JSON.parse(fs.readFileSync(path.join(R, p), 'utf8'));
const db = ShipDatabase.fromMany([j('data/ships_axis.json'), j('data/ships_allied.json')]);
const sc = j('data/scenarios.json').scenarios.find((s) => s.id === 'denmark_strait_1941');
const w = new World({ scenario: sc, database: db, seed: 20261017, playerSide: 'ALLIED', aiOpts: { backend: 'LOCAL' } });
w.advance(200);
const ai = new AICommander('AXIS', w, { backend: 'REMOTE' });
const s1 = ai.buildState();
console.log('外部智能体收到的 state 顶层字段：' + Object.keys(s1).join(', '));
console.log('context 字段：' + Object.keys(s1.context).join(', '));
console.log('体积：state=' + JSON.stringify(s1).length + ' 字符，其中 doctrine=' + (s1.context.doctrine || '').length + '，briefing=' + s1.context.briefing.length + '，events=' + s1.context.events.length + ' 条，orders=' + s1.context.orders.length + ' 条，trackMemory=' + s1.context.trackMemory.length + ' 个');
w.advance(120);
const s2 = ai.buildState();
console.log('第二次推送：含 doctrine=' + (!!s2.context.doctrine) + '（只在首次发一次），state=' + JSON.stringify(s2).length + ' 字符，战况=' + s2.context.events.length + ' 条');
console.log('简报节选：\n' + s1.context.briefing.slice(0, 500));
