import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { World } from '../src/sim/world.js';
import { ShipDatabase } from '../src/sim/data.js';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const R = path.join(__dirname, '..');
const j = (p) => JSON.parse(fs.readFileSync(path.join(R, p), 'utf8'));
const db = ShipDatabase.fromMany([j('data/ships_axis.json'), j('data/ships_allied.json')]);
const sc = j('data/scenarios.json').scenarios.find((s) => s.id === 'denmark_strait_1941');
const w = new World({ scenario: sc, database: db, seed: 7, playerSide: 'ALLIED', aiOpts: { backend: 'LOCAL' } });
const ai = w.ai['AXIS'];
ai.connectLLM('', { model: 'stub', maxTokens: 500, compact: true });
ai.setLLMCall(async () => JSON.stringify({ reasoning: 'stub', intent: 'stub', commands: [{ shipId: 'bismarck', kind: 'SET_COURSE', params: { heading: 200 } }] }));
ai.intervalS = 1;
console.log('初始：backend=' + ai.backend + ' linkState=' + ai.linkState + ' llmCall=' + typeof ai.llmCall + ' intervalS=' + ai.intervalS);
w.advance(30);
const s = ai.status || {};
console.log('30s 后：linkState=' + ai.linkState + ' pending=' + ai.pendingRequest + ' decisions=' + (s.decisions || 0) + ' errors=' + (s.lastError || '无') + ' timeouts=' + (s.timeouts || 0));
console.log('事件：ai.decision=' + w.events.history.filter((e) => e.type === 'ai.decision').length + ' ai.error=' + w.events.history.filter((e) => e.type === 'ai.error').length + ' ai.connected=' + w.events.history.filter((e) => e.type === 'ai.connected').length);
const errs = w.events.history.filter((e) => e.type === 'ai.error').slice(-3);
for (const e of errs) console.log('  错误：' + e.code + ' ' + e.message);
console.log('命令来源：' + JSON.stringify(w.commands.reduce((a, c) => { a[c.source] = (a[c.source] || 0) + 1; return a; }, {})));
console.log('俾斯麦 _directiveSim=' + (w.ship('bismarck')._directiveSim === undefined ? '未设置' : w.ship('bismarck')._directiveSim));
