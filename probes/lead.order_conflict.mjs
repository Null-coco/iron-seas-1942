import fs from 'node:fs';
import { World } from '../src/sim/world.js';
import { ShipDatabase } from '../src/sim/data.js';
const j = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const db = ShipDatabase.fromMany([j('data/ships_axis.json'), j('data/ships_allied.json')]);
const sc = j('data/scenarios.json').scenarios.find((s) => s.id === 'sandbox');
const w = new World({ scenario: sc, database: db, seed: 1, playerSide: 'ALLIED', aiOpts: { backend: 'LOCAL' } });
for (const s of ['ALLIED', 'AXIS']) w.ai[s].autoCommand = true;
w.advance(120);
const sd = w.ship('sandbox_sd');
console.log('指令前：航向 ' + Math.round(sd.commanded.heading) + '  _directiveSim=' + sd._directiveSim);
w.issueCommand({ side: 'ALLIED', shipId: sd.id, kind: 'SET_COURSE', params: { heading: 240 }, scope: 'SHIP' }, { source: 'PLAYER' });
console.log('下令人后立刻：_directiveSim=' + sd._directiveSim + '（当前 t=' + Math.round(w.t) + '）');
const n0 = w.commands.length;
w.advance(40);
console.log('40s 后：指令航向 ' + Math.round(sd.commanded.heading) + '（期望 240）');
const after = w.commands.slice(n0).filter((c) => c.shipId === sd.id);
console.log('这 40s 内针对该舰的命令 ' + after.length + ' 条：');
for (const c of after.slice(0, 10)) console.log('  t=' + Math.round(c.t_issue) + ' → ' + Math.round(c.t_effective) + ' ' + c.source + ' ' + c.kind + ' ' + JSON.stringify(c.params));
console.log('本地 AI 的 directiveHoldS=' + w.ai['ALLIED'].local.directiveHoldS + '  该舰 _directiveSim=' + sd._directiveSim);
